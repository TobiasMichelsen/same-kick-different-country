# Step 3: make the artist list for the suggestions in the annotation tool
#
# Artists come from:
#   - annotations/artists_curated.txt (our own list with aliases, edit this one)
#   - artists from Track/Mix post titles that show up at least 3 times
#     (without things like radio shows, "Various Artists", set names)
#
# Output: annotations/artists.js
# It's .js and not .json because then the tool can open it without a server.
# Run from the repo root: python src/02_annotation/03_build_artist_list.py

import argparse
import json
import re
import unicodedata
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
CURATED = ROOT / "annotations" / "artists_curated.txt"
POSTS = ROOT / "data" / "processed" / "reddit_techno_posts.csv"
OUT = ROOT / "annotations" / "artists.js"

NOT_ARTIST = re.compile(
    r"\b(radio|various|set|mix|mixtape|live|podcast|episode|ep|album|records?|"
    r"present|presents|vs\.?|b2b|techno|dj set)\b|[|,&]|\d{4}", re.I)


# lowercase + no accents, so "Âme" and "ame" count as the same name
def fold(s):
    s = unicodedata.normalize("NFD", s)
    return "".join(c for c in s if unicodedata.category(c) != "Mn").casefold().strip()


def read_curated():
    entries = []
    for line in CURATED.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip() if line.lstrip().startswith("#") else line.strip()
        if line:
            entries.append([n.strip() for n in line.split("|") if n.strip()])
    return entries


def read_reddit(min_count):
    df = pd.read_csv(POSTS)
    names = df[df["subgenre_flair"].isin(["Track", "Mix"])]["artist"].dropna().str.strip()
    counts = names.value_counts()
    keep = [n for n, c in counts.items()
            if c >= min_count and 2 <= len(n) <= 40 and not NOT_ARTIST.search(n)]
    return [[n] for n in keep]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-count", type=int, default=3)
    args = ap.parse_args()

    merged, seen = [], {}
    for source, entries in [("curated", read_curated()), ("reddit", read_reddit(args.min_count))]:
        added = 0
        for names in entries:
            hit = next((seen[fold(n)] for n in names if fold(n) in seen), None)
            if hit is not None:                   # already have this artist, just add the new aliases
                entry = merged[hit]
                for a in names:
                    if fold(a) not in seen:
                        entry.append(a)
                        seen[fold(a)] = hit
                continue
            for n in names:
                seen[fold(n)] = len(merged)
            merged.append(names)
            added += 1
        print(f"{source}: {added} artists")

    merged.sort(key=lambda e: fold(e[0]))
    OUT.write_text(
        "// Generated by src/02_annotation/03_build_artist_list.py: edit artists_curated.txt instead.\n"
        "window.ARTISTS = [\n"
        + ",\n".join(json.dumps(e, ensure_ascii=False) for e in merged)
        + "\n];\n",
        encoding="utf-8")
    print(f"Saved {len(merged)} artists -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
